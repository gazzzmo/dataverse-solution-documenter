def _generate_entities(
    entities: list[dict[str, Any]],
    relationships: list[dict[str, Any]] | None = None,
) -> str:
    lines = [_h(1, "Entities & Tables"), ""]

    if not entities:
        lines.append("_No entities found in customizations.xml._")
        return "\n".join(lines)

    lines += [f"**Total entities:** {len(entities)}", ""]

    # Pre-calculate relationships per entity
    rels = relationships or []
    rels_by_entity: dict[str, list[dict[str, Any]]] = {}
    for r in rels:
        e1 = (r.get("entity1") or "").lower()
        e2 = (r.get("entity2") or "").lower()
        if e1:
            rels_by_entity.setdefault(e1, []).append(r)
        if e2 and e2 != e1:
            rels_by_entity.setdefault(e2, []).append(r)

    # Summary table
    lines += [
        _h(2, "Summary"),
        "",
        _table(
            ["Display Name", "Schema Name", "Attributes", "Forms", "Views"],
            [
                [
                    f"[{e.get('display_name') or e.get('name', '')}](#{(e.get('display_name') or e.get('name', '')).lower().replace(' ', '-').replace('_', '-')})",
                    _badge(e.get("name", "")),
                    str(len(e.get("attributes", []))),
                    str(len(e.get("forms", []))),
                    str(len(e.get("views", []))),
                ]
                for e in entities
            ],
        ),
        "",
        "---",
        "",
    ]

    for entity in entities:
        display = entity.get("display_name") or entity.get("name", "Unknown")
        schema = entity.get("name", "")
        lines += [_h(2, display), ""]

        lines += [
            _table(
                ["Field", "Value"],
                [
                    ["Schema Name", _badge(schema)],
                    ["Display Name", display],
                    ["Collection Name", entity.get("collection_name", "")],
                    ["Description", entity.get("description", "")],
                ],
            ),
            "",
        ]

        attrs = entity.get("attributes", [])
        if attrs:
            lines += [_h(3, "Attributes"), ""]
            attr_rows = []
            for attr in attrs:
                req = attr.get("required", "none")
                req_icon = "✅" if req == "required" else ("⚠️" if req == "systemrequired" else "")
                options_str = ""
                if attr.get("options"):
                    options_str = "; ".join(
                        f"{o['value']}: {o['label']}" for o in attr["options"][:5]
                    )
                    if len(attr["options"]) > 5:
                        options_str += f" (+{len(attr['options'])-5} more)"
                elif attr.get("optionset_name"):
                    options_str = f"OptionSet: `{attr['optionset_name']}`"
                attr_rows.append([
                    _badge(attr.get("name", "")),
                    attr.get("display_name", ""),
                    attr.get("type", ""),
                    req_icon or req,
                    options_str,
                ])
            lines += [
                _table(["Schema Name", "Display Name", "Type", "Required", "Options / References"], attr_rows),
                "",
            ]

        forms = entity.get("forms", [])
        if forms:
            lines += [
                _h(3, "Forms"),
                "",
                _table(
                    ["Name", "ID", "Version", "Active"],
                    [
                        [
                            f.get("name", ""),
                            _badge(f.get("id", "")),
                            f.get("version", ""),
                            "✅" if f.get("active") else "❌",
                        ]
                        for f in forms
                    ],
                ),
                "",
            ]

        views = entity.get("views", [])
        if views:
            lines += [
                _h(3, "Views"),
                "",
                _table(
                    ["Name", "Type"],
                    [[v.get("name", ""), v.get("type", "")] for v in views],
                ),
                "",
            ]

        # Entity Dependencies & References
        ent_rels = rels_by_entity.get(schema.lower(), [])
        form_libs = []
        for f in forms:
            for lib in f.get("libraries", []):
                if lib not in form_libs:
                    form_libs.append(lib)

        opt_sets_used = []
        for attr in attrs:
            opt_name = attr.get("optionset_name")
            if opt_name and opt_name not in opt_sets_used:
                opt_sets_used.append(opt_name)

        if ent_rels or form_libs or opt_sets_used:
            lines += [_h(3, "Dependencies & References"), ""]
            if ent_rels:
                lines += [
                    f"**Relationships ({len(ent_rels)}):**  ",
                ]
                rel_rows = []
                for r in ent_rels:
                    other_ent = r.get("entity2") if (r.get("entity1") or "").lower() == schema.lower() else r.get("entity1")
                    rel_rows.append([
                        _badge(r.get("name", "")),
                        r.get("type", "") or "OneToMany",
                        _badge(other_ent or "—"),
                        _badge(r.get("referencing_attribute", "")) if r.get("referencing_attribute") else "—",
                    ])
                lines += [
                    _table(["Relationship", "Type", "Related Table", "Lookup Attribute"], rel_rows),
                    "",
                ]

            if opt_sets_used:
                lines += [
                    f"**Referenced Option Sets:** {', '.join(_badge(o) for o in opt_sets_used)}  ",
                ]
            if form_libs:
                lines += [
                    f"**Form Web Resources (Scripts/Libraries):** {', '.join(_badge(lib) for lib in form_libs)}  ",
                ]
            lines.append("")

        lines += ["---", ""]

    return "\n".join(lines)


