def _generate_index(parsed: dict[str, Any], solution_name: str) -> str:
    sol = parsed.get("solution", {})
    lines = [
        _h(1, f"{sol.get('display_name', solution_name)} — Solution Documentation"),
        "",
        "> Generated by **Dataverse Solution Documenter**",
        "",
        _h(2, "Contents"),
        "",
        _table(
            ["Document", "Description"],
            [
                ["[Solution Overview](solution-overview.md)", "Metadata, publisher, version, component summary"],
                ["[Entities & Tables](entities.md)", f"Entities ({len(parsed.get('entities', []))})"],
                ["[Workflows](workflows.md)", f"Workflows ({len(parsed.get('workflows', []))})"],
                ["[Web Resources](web-resources.md)", f"Web resources ({len(parsed.get('webresources', []))})"],
                ["[Environment Variables](environment-variables.md)", f"Environment variable definitions ({len(parsed.get('env_vars', []))})"],
                ["[Security Roles](security-roles.md)", f"Roles ({len(parsed.get('roles', []))})"],
                ["[Entity Relationships](relationships.md)", f"Relationships ({len(parsed.get('entity_relationships', []))})"],
                ["[Connection References](connection-references.md)", f"Connection references ({len(parsed.get('connection_references', []))})"],
                ["[App Modules](app-modules.md)", f"Model-driven apps ({len(parsed.get('app_modules', []))})"],
            ],
        ),
        "",
        "---",
        "",
        f"**Solution:** {_badge(sol.get('unique_name', 'N/A'))}  ",
        f"**Version:** {_badge(sol.get('version', 'N/A'))}  ",
        f"**Publisher:** {sol.get('publisher_name', 'N/A')} ({_badge(sol.get('publisher_prefix', ''))})  ",
        f"**Managed:** {'Yes' if sol.get('is_managed') == '1' else 'No'}  ",
    ]
    return "\n".join(lines)


