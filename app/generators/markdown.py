# Solution Overview
# ---------------------------------------------------------------------------

def _generate_solution_overview(solution: dict[str, Any]) -> str:
    lines = [
        _h(1, "Solution Overview"),
        "",
        _h(2, "Metadata"),
        "",
        _table(
            ["Field", "Value"],
            [
                ["Unique Name", _badge(solution.get("unique_name", ""))],
                ["Display Name", solution.get("display_name", "")],
                ["Version", _badge(solution.get("version", ""))],
                ["Managed", "Yes" if solution.get("is_managed") == "1" else "No"],
                ["Publisher", solution.get("publisher_name", "")],
                ["Publisher Unique Name", _badge(solution.get("publisher_unique_name", ""))],
                ["Customization Prefix", _badge(solution.get("publisher_prefix", ""))],
                ["Option Value Prefix", solution.get("publisher_option_prefix", "")],
                ["Total Root Components", str(solution.get("component_count", 0))],
            ],
        ),
        "",
    ]

    if solution.get("description"):
        lines += [_h(2, "Description"), "", solution["description"], ""]

    if solution.get("publisher_description"):
        lines += [_h(2, "Publisher Description"), "", solution["publisher_description"], ""]

    component_types = solution.get("component_types", {})
    if component_types:
        lines += [
            _h(2, "Component Breakdown"),
            "",
            _table(
                ["Component Type", "Count"],
                [[ctype, str(count)] for ctype, count in sorted(component_types.items())],
            ),
            "",
        ]

    return "\n".join(lines)


