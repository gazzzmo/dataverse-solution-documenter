def _generate_workflows(workflows: list[dict[str, Any]]) -> str:
    lines = [_h(1, "Workflows"), ""]

    if not workflows:
        lines.append("_No workflows found in this solution._")
        return "\n".join(lines)

    lines += [f"**Total workflows:** {len(workflows)}", ""]

    # Group by category
    by_category: dict[str, list] = {}
    for wf in workflows:
        cat = wf.get("category", "Unknown")
        by_category.setdefault(cat, []).append(wf)

    for category, wfs in sorted(by_category.items()):
        lines += [_h(2, category), ""]
        for wf in wfs:
            lines += [_h(3, wf.get("name", "Unnamed")), ""]

            rows: list[list[str]] = [
                ["Category", wf.get("category", "")],
                ["Primary Entity", wf.get("primary_entity", "") or "N/A"],
                ["State", wf.get("state", "")],
                ["Introduced Version", wf.get("introduced_version", "")],
            ]
            if wf.get("description"):
                rows.insert(0, ["Description", wf["description"]])

            trigger_flags = []
            if wf.get("on_demand"):
                trigger_flags.append("On Demand")
            if wf.get("trigger_on_create"):
                trigger_flags.append("On Create")
            if wf.get("trigger_on_delete"):
                trigger_flags.append("On Delete")
            if trigger_flags:
                rows.append(["Classic Trigger", ", ".join(trigger_flags)])

            lines += [_table(["Field", "Value"], rows), ""]

            if wf.get("triggers"):
                lines += [
                    f"**Triggers:** {', '.join(_badge(t) for t in wf['triggers'])}  ",
                ]
            if wf.get("actions"):
                lines += [
                    f"**Actions:** {', '.join(_badge(a) for a in wf['actions'])}  ",
                ]
            if wf.get("connection_refs"):
                lines += [
                    f"**Connection References:** {', '.join(_badge(c) for c in wf['connection_refs'])}  ",
                ]
            if wf.get("env_vars"):
                lines += [
                    f"**Environment Variables:** {', '.join(_badge(ev) for ev in wf['env_vars'])}  ",
                ]
            if wf.get("dataverse_entities"):
                lines += [
                    f"**Dataverse Tables Accessed:** {', '.join(_badge(de) for de in wf['dataverse_entities'])}  ",
                ]

            if wf.get("file"):
                lines += [f"**Source File:** `{wf['file']}`  "]

            lines.append("")

        lines += ["---", ""]

    return "\n".join(lines)


